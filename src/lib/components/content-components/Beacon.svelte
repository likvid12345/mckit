<div class="beacon-wrapper">
	<h1 class="page-title">Beacon Guide</h1>
	<p class="intro">This is the simplest beacon guide ever. Let's dive right into it.</p>

	<div class="gray-container">
		<h2>Beacon is made out of 2 parts:</h2>
		<ul>
			<li>The beacon itself</li>
			<li>Beacon pyramid</li>
		</ul>
	</div>

	<h2 class="section-title">What is beacon?</h2>
	<p>
		Beacon is a structure that gives you power ups in a certain area, beacon area is based on a
		beacon level
	</p>

	<div class="gray-container">
		<h2>How to make the beacon:</h2>
		<p class="container-sub">You will need the following stuff:</p>
		<ul>
			<li>3 obsidian blocks</li>
			<li>5 glass blocks</li>
			<li>1 Nether Star</li>
		</ul>
	</div>

	<h2 class="section-title">How to obtain a Nether Star?</h2>
	<p>
		The Nether Star is dropped by the Wither, a powerful boss mob. To spawn the Wither, you need to
		place 4 blocks of soul sand (or soul soil) in a T-shape, then place 3 Wither Skeleton Skulls on
		top. Wither Skeleton Skulls are a rare drop from Wither Skeletons found in Nether Fortresses.
	</p>

	<div class="gray-container">
		<h2>Beacon pyramid levels:</h2>
		<p class="container-sub">
			The pyramid gives your beacon its power. The bigger the pyramid, the stronger the effect:
		</p>
		<ul>
			<li>Level 1 (1 layer) — 1 power up, 20 block radius</li>
			<li>Level 2 (2 layers) — 2 power ups, 30 block radius</li>
			<li>Level 3 (3 layers) — 3 power ups, 40 block radius</li>
			<li>Level 4 (4 layers) — 4 power ups, 50 block radius</li>
		</ul>
	</div>

	<h2 class="section-title">What blocks can I use for the pyramid?</h2>
	<p>
		The pyramid must be built out of one of the following: Iron Block, Gold Block, Emerald Block,
		Diamond Block, or Netherite Block. You can mix different block types across layers if you'd
		like.
	</p>

	<div class="gray-container">
		<h2>Available power ups:</h2>
		<ul>
			<li>Speed</li>
			<li>Haste</li>
			<li>Resistance</li>
			<li>Jump Boost</li>
			<li>Strength</li>
			<li>Regeneration (only at level 4)</li>
		</ul>
	</div>
</div>

